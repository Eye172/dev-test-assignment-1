const terminal = ["completed", "needs_attention", "failed", "cancelled"];
const ownerOf: Record<SectionKey, "strategist" | "monetizer"> = { icp: "strategist", value: "strategist", channels: "strategist", assumptions: "strategist", pricing: "monetizer" };
const modeText: Record<RunMode, string> = { full: "Full review", research: "Market research", strategy: "Strategy", pricing: "Pricing", experiments: "Experiments" };
const statusText: Record<AiRun["status"], string> = { queued: "Queued", running: "Working", paused: "Paused", completed: "Reviewed", needs_attention: "Needs your attention", failed: "Failed", cancelled: "Cancelled" };
const money = (micros: number) => `$${(micros / 1_000_000).toFixed(2)}`;

/** Newest completed revision of a role in a run. */
function latest(run: AiRun, role: AiStep["role"]) {
  return [...run.steps].filter(s => s.role === role && s.status === "completed" && s.result).sort((a, b) => b.round - a.round)[0];
}

/** Flatten a section value into labelled rows so saved and proposed text can be read side by side. */
function rows(key: SectionKey, data: unknown): [string, string][] {
  const d = (data ?? {}) as Record<string, unknown>;
  if (key === "channels") {
    const c = (d.channels as { name: string; reason: string }[] | undefined) ?? [];
    return [...c.map((x, i) => [`Channel ${i + 1}`, [x.name, x.reason].filter(Boolean).join(" — ")] as [string, string]), ["First experiment", String(d.firstExperiment ?? "")]];
  }
  if (key === "assumptions") {
    const a = (d.assumptions as { statement: string; risk: string; validationMethod: string }[] | undefined) ?? [];
    return a.map((x, i) => [`Assumption ${i + 1} · ${x.risk} risk`, [x.statement, x.validationMethod && `Test: ${x.validationMethod}`].filter(Boolean).join("\n")]);
  }
  return Object.entries(d).map(([k, v]) => [fieldLabels[k] ?? k, String(v ?? "")]);
}

export function AiStudio({ compact = false }: { compact?: boolean }) {
  const { workspace, setWorkspace, notify } = useWorkspace();
  const hydrated = useHydrated();
  const base = `/api/startups/${workspace.startup.id}/ai`;
  const [state, setState] = useState<AiStudioState | null>(null);
  const [error, setError] = useState<Error | null>(null);
  const [selected, setSelected] = useState<string | null>(null);
  const load = useCallback(async () => { try { const s = await api<AiStudioState>(base); setState(s); setError(null); return s; } catch (e) { setError(e as Error); return null; } }, [base]);
  useEffect(() => {
    let alive = true;
    api<AiStudioState>(base).then(next => { if (alive) setState(next); }).catch(e => { if (alive) setError(e as Error); });
    return () => { alive = false; };
  }, [base]);
  const run = state?.runs.find(r => r.id === selected) ?? state?.runs[0] ?? null;
  const active = !!run && !terminal.includes(run.status);
  // Poll only while a run is active and the tab is visible (contract: ~3 s, back off when hidden).
  useEffect(() => {
    if (!active) return;
    let t: ReturnType<typeof setTimeout>;
    const tick = async () => { if (document.visibilityState === "visible") await load(); t = setTimeout(tick, document.visibilityState === "visible" ? 3000 : 10000); };
    t = setTimeout(tick, 3000);
    return () => clearTimeout(t);
  }, [active, load]);

  if (!state) return <section className="studio plate" aria-busy="true"><p className="field-help">{error ? "" : "Loading AI studio…"}</p><ErrorNotice error={error} onRetry={() => void load()}/></section>;
  if (!state.configured) return <section className="studio plate quiet-studio"><div className="studio-head"><Sparkles size={18} aria-hidden/><h2>AI specialists</h2></div>
    <p className="muted">Not configured on this deployment. Everything else runs on transparent rules; nothing here is generated by AI.</p></section>;
  if (!state.authorized) return <Unlock base={base} onDone={() => void load()} compact={compact}/>;

  return <section className={`studio ${compact ? "compact" : ""}`} aria-labelledby="studio-title">
    <div className="studio-head">
      <Sparkles size={18} aria-hidden/><h2 id="studio-title">{compact ? "AI specialists" : "Runs"}</h2>
      <span className="studio-budget faint">Budget {money(state.limits.runBudgetUsd * 1_000_000)} per run · {money(state.limits.dailyBudgetUsd * 1_000_000)} per day</span>
      <button type="button" className="button small ghost" onClick={async () => { await api(base, { method: "POST", body: JSON.stringify({ action: "lock" }) }); void load(); }}><Lock size={14} aria-hidden/>Lock</button>
    </div>
    <ErrorNotice error={error} onRetry={() => void load()}/>
    {!active && <NewRun base={base} parentRunId={run?.id ?? null} onCreated={id => { setSelected(id); void load(); }}/>}
    {state.runs.length > 1 && <div className="run-tabs" role="tablist" aria-label="Runs">{state.runs.slice(0, 6).map(r =>
      <button key={r.id} role="tab" aria-selected={r.id === run?.id} className={r.id === run?.id ? "on" : ""} onClick={() => setSelected(r.id)}>
        {modeText[r.mode]}<span className={`run-dot ${r.status}`}/><span className="faint">{new Date(r.createdAt).toISOString().slice(5, 16).replace("T", " ")}</span></button>)}</div>}
    {run ? <RunView run={run} workspace={workspace} base={base} hydrated={hydrated} onChanged={async ws => { if (ws) setWorkspace(ws); await load(); }} notify={notify}/>
      : <p className="studio-empty">No runs yet. Start one with your brief above — specialists draft, a critic reviews, and you decide what to apply.</p>}
  </section>;
}

function Unlock({ base, onDone, compact }: { base: string; onDone: () => void; compact: boolean }) {
  const [code, setCode] = useState(""); const [busy, setBusy] = useState(false); const [error, setError] = useState<Error | null>(null);
  return <section className={`studio plate quiet-studio ${compact ? "compact" : ""}`} aria-labelledby="unlock-title">
    <div className="studio-head"><KeyRound size={18} aria-hidden/><h2 id="unlock-title">AI specialists</h2></div>
    <p className="muted">AI runs cost real money, so they are limited to the owner’s access code. Without it, the workspace works on transparent rules.</p>
    <form className="unlock" onSubmit={async e => { e.preventDefault(); setBusy(true); setError(null);
      try { await api(base, { method: "POST", body: JSON.stringify({ action: "unlock", payload: { code } }) }); setCode(""); onDone(); } catch (err) { setError(err as Error); } finally { setBusy(false); } }}>
      <label className="sr-only" htmlFor="ai-code">Access code</label>
      <input id="ai-code" className="input" type="password" autoComplete="off" value={code} onChange={e => setCode(e.target.value)} placeholder="Access code"/>
      <button className="button small" disabled={!code || busy} aria-busy={busy}>{busy ? <Spinner/> : "Unlock"}</button>
    </form>
    <ErrorNotice error={error}/>
  </section>;
}

function NewRun({ base, parentRunId, onCreated }: { base: string; parentRunId: string | null; onCreated: (id: string) => void }) {
  const [mode, setMode] = useState<RunMode>("full"); const [brief, setBrief] = useState(""); const [busy, setBusy] = useState(false); const [error, setError] = useState<Error | null>(null);
  const [requestId, setRequestId] = useState(() => crypto.randomUUID());
  return <form className="new-run" onSubmit={async e => { e.preventDefault(); setBusy(true); setError(null);
    try { const r = await api<{ id: string }>(base, { method: "POST", body: JSON.stringify({ action: "create", payload: { mode, brief, requestId, ...(parentRunId ? { parentRunId } : {}) } }) }); setRequestId(crypto.randomUUID()); setBrief(""); onCreated(r.id); }
    catch (err) { setError(err as Error); } finally { setBusy(false); } }}>
    <div className="chip-row" role="radiogroup" aria-label="What to review">{runModes.map(m => <button type="button" role="radio" aria-checked={mode === m} key={m} className={`chip ${mode === m ? "on" : ""}`} onClick={() => setMode(m)}>{modeText[m]}</button>)}</div>
    <p className="field-help">{modeRoles[mode].map(r => agentCatalog[r].short).join(" → ")}{parentRunId ? " · builds on the latest run and your recorded evidence" : ""}</p>
    <label className="sr-only" htmlFor="run-brief">Brief</label>
    <textarea id="run-brief" className="input" rows={3} maxLength={6000} value={brief} onChange={e => setBrief(e.target.value)} placeholder="What should they focus on? Goals, constraints, what you already tried, what worries you."/>
    <ErrorNotice error={error}/>
    <button className="button primary small" disabled={busy} aria-busy={busy}>{busy ? <><Spinner/>Starting…</> : <><Play size={14} aria-hidden/>Start {modeText[mode].toLowerCase()}</>}</button>
  </form>;
}

function RunView({ run, workspace, base, hydrated, onChanged, notify }: { run: AiRun; workspace: Workspace; base: string; hydrated: boolean; onChanged: (ws?: Workspace) => Promise<void>; notify: (m: string) => void }) {
  const [busy, setBusy] = useState<string | null>(null); const [error, setError] = useState<Error | null>(null);
  const act = async (key: string, body: object, message?: string) => {
    setBusy(key); setError(null);
    try { const r = await api<Workspace | { id: string }>(base, { method: "POST", body: JSON.stringify(body) }); await onChanged("startup" in r ? r : undefined); if (message) notify(message); }
    catch (e) { setError(e as Error); } finally { setBusy(null); }
  };
  const roles = [...new Set(run.steps.map(s => s.role))];
  const critic = latest(run, "critic");
  const applied = new Set(run.applications.map(a => `${a.stepId}:${a.target}`));
  const experimenter = latest(run, "experimenter");
  const proposals = useMemo(() => sectionKeys.map(key => {
    const step = latest(run, ownerOf[key]); const proposal = step?.result?.strategy[key];
    return step && proposal ? { key, step, proposal } : null;
  }).filter(Boolean) as { key: SectionKey; step: AiStep; proposal: unknown }[], [run]);
  const terminalRun = terminal.includes(run.status);

  return <div className="run">
    <div className="run-status">
      <span className={`run-pill ${run.status}`}>{!terminalRun && <span className="run-live" aria-hidden/>}{statusText[run.status]}</span>
      <span className="faint num">{run.inputTokens + run.outputTokens > 0 ? `${(run.inputTokens + run.outputTokens).toLocaleString()} tokens · est. ${money(run.estimatedMicros)}` : ""}</span>
      {run.stale && <span className="run-stale"><AlertTriangle size={14} aria-hidden/>Your workspace changed since this run started</span>}
      <span className="run-actions">
        {run.status === "paused" && <button type="button" className="button small" disabled={!!busy || !hydrated} onClick={() => void act("resume", { action: "resume", runId: run.id })}><Play size={14} aria-hidden/>Resume</button>}
        {!terminalRun && <button type="button" className="button small ghost" disabled={!!busy || !hydrated} onClick={() => void act("cancel", { action: "cancel", runId: run.id }, "Run cancelled")}><Square size={13} aria-hidden/>Cancel</button>}
      </span>
    </div>
    {run.error && <p className="info-notice">{run.error}</p>}
    <ErrorNotice error={error}/>

    <ol className="role-track" aria-label="Specialists">{roles.map(role => {
      const steps = run.steps.filter(s => s.role === role); const last = steps[steps.length - 1];
      return <li key={role} className={last.status}>
        <span className="role-mark" aria-hidden>{last.status === "completed" ? <Check size={12} strokeWidth={3}/> : last.status === "running" ? <span className="role-spin"/> : last.status === "failed" ? "!" : ""}</span>
        <span className="role-name">{agentCatalog[role].short}</span>
        {steps.length > 1 && <span className="faint">rev {steps.length}</span>}
      </li>;
    })}</ol>

    {!terminalRun && run.events.length > 0 && <p className="run-event" aria-live="polite"><span className="run-live" aria-hidden/>{run.events[run.events.length - 1].message}</p>}

    {critic?.result && <Findings result={critic.result}/>}

    {proposals.length > 0 && <section className="proposals" aria-labelledby="prop-title">
      <h3 id="prop-title" className="label">Proposals · compare and apply</h3>
      {proposals.map(({ key, step, proposal }, index) => {
        const saved = workspace.sections.find(s => s.key === key)?.data;
        const done = applied.has(`${step.id}:${key}`);
        const blocked = critic?.result?.issues.some(i => i.severity === "blocking" && i.target === step.role);
        return <details key={key} className="proposal" open={index === 0 || proposals.length <= 2}>
          <summary><span className="proposal-title">{sectionTitles[key]}</span><span className="faint">by {agentCatalog[step.role].short}{step.round ? ` · revision ${step.round + 1}` : ""}</span>
            {done ? <span className="badge complete"><Check size={11} aria-hidden/>Applied</span> : blocked ? <span className="badge high">Critic blocked</span> : <span className="badge draft">Draft · untested</span>}</summary>
          <div className="compare">
            <div><p className="label">Saved now</p>{rows(key, saved).map(([l, v]) => <p key={l} className="cmp-row"><span>{l}</span>{v || <em className="faint">empty</em>}</p>)}</div>
            <div className="proposed"><p className="label">Proposed</p>{rows(key, proposal).map(([l, v]) => <p key={l} className="cmp-row"><span>{l}</span>{v || <em className="faint">empty</em>}</p>)}</div>
          </div>
          {!done && <div className="proposal-actions">
            <button type="button" className="button small primary" disabled={!!busy || !hydrated || run.stale} aria-busy={busy === key}
              onClick={() => void act(key, { action: "apply", runId: run.id, stepId: step.id, target: key }, `${sectionTitles[key]} updated from the proposal`)}>
              {busy === key ? <><Spinner/>Applying…</> : <>Apply to {sectionTitles[key]}</>}</button>
            <span className="field-help">Replaces the saved section. Your notes are kept; the change is recorded and visible to anyone with the link.</span>
          </div>}
        </details>;
      })}
    </section>}

    {experimenter?.result && experimenter.result.experiments.length > 0 && <section className="proposals" aria-labelledby="exp-title">
      <h3 id="exp-title" className="label">Experiment plan · {experimenter.result.experiments.length} tasks</h3>
      <ol className="exp-list">{experimenter.result.experiments.map((x, i) => <li key={i}><span className="faint num">W{x.week}</span><div><p className="exp-title">{x.title}</p><p className="faint">{x.metric} · threshold {x.threshold}</p></div></li>)}</ol>
      {!applied.has(`${experimenter.id}:roadmap`) ? <button type="button" className="button small" disabled={!!busy || !hydrated || run.stale}
        onClick={() => void act("roadmap", { action: "apply", runId: run.id, stepId: experimenter.id, target: "roadmap" }, "AI experiments added to the roadmap")}>
        {busy === "roadmap" ? <><Spinner/>Adding…</> : "Add to roadmap"}</button> : <span className="badge complete"><Check size={11} aria-hidden/>Added to roadmap</span>}
    </section>}

    {run.sources.length > 0 && <details className="disclosure sources"><summary>Sources ({run.sources.length})</summary>
      <ul>{run.sources.map(s => <li key={s.url}><a className="text-link" href={s.url} target="_blank" rel="noopener noreferrer">{s.title || new URL(s.url).hostname}<ExternalLink size={12} className="inline-icon" aria-hidden/></a></li>)}</ul></details>}
    {terminalRun && <p className="field-help run-foot"><RotateCcw size={13} aria-hidden/> To revise, start a follow-up above — it builds on this run and any evidence you record.</p>}
    {run.status === "paused" && <p className="field-help"><Pause size={13} aria-hidden/> Paused at a safe checkpoint. Resume continues without repeating finished steps.</p>}
  </div>;
}


function Findings({ result }: { result: AiResult }) {
  const issues = result.issues.filter(i => i.severity !== "minor");
  return <section className="findings" aria-labelledby="find-title">
    <h3 id="find-title" className="label">Critic’s review</h3>
    <p className="findings-summary">{result.summary}</p>
    <AnimatePresence initial={false}>{issues.map((i, n) => <motion.div key={n} className={`issue ${i.severity}`} initial={{ opacity: 0, y: 6 }} animate={{ opacity: 1, y: 0 }}>
      <span className="issue-tag">{i.severity}</span><p><strong>{i.topic}.</strong> {i.reason} <span className="faint">Fix: {i.correction}</span></p>
    </motion.div>)}</AnimatePresence>
    {result.questions.length > 0 && <ul className="questions">{result.questions.map((q, n) => <li key={n}><strong>{q.question}</strong> <span className="faint">{q.why}</span></li>)}</ul>}
  </section>;
}
