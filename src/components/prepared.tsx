"use client";
import { useEffect, useState } from "react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { motion } from "motion/react";
import { ArrowRight, FileEdit, Route, Sparkles, X } from "lucide-react";
import { api } from "@/lib/client-api";
import { sectionTitles } from "@/lib/domain/completion";
import { sectionKeys, type SectionKey } from "@/lib/domain/schemas";
import type { AiStudioState } from "@/lib/domain/ai";
import { useHasDraft } from "./draft-recovery";
import { useWorkspace, easeOut } from "./workspace";

/** First screen after onboarding: what exists now and what is waiting for the founder's decision. */
export function PreparedPanel() {
  const { workspace } = useWorkspace(); const router = useRouter();
  const base = `/startups/${workspace.startup.id}`;
  const id = workspace.startup.id;
  const has: Record<SectionKey, boolean> = { icp: useHasDraft(`strategy:${id}:icp`), value: useHasDraft(`strategy:${id}:value`), channels: useHasDraft(`strategy:${id}:channels`), pricing: useHasDraft(`strategy:${id}:pricing`), assumptions: useHasDraft(`strategy:${id}:assumptions`) };
  const drafts = sectionKeys.filter(k => has[k]);
  const [ai, setAi] = useState<AiStudioState | null>(null);
  useEffect(() => { let alive = true; api<AiStudioState>(`/api/startups/${id}/ai`).then(s => { if (alive) setAi(s); }).catch(() => {}); return () => { alive = false; }; }, [id]);
  const tasks = workspace.tasks.filter(t => !t.archived).length;
  const run = ai?.runs[0];
  return <motion.section className="prepared" aria-labelledby="prepared-title" initial={{ opacity: 0, y: -8 }} animate={{ opacity: 1, y: 0 }} transition={{ duration: 0.4, ease: easeOut }}>
    <div className="prepared-head"><h2 id="prepared-title">Prepared for you</h2>
      <button type="button" className="icon-button small" aria-label="Dismiss" onClick={() => router.replace(base, { scroll: false })}><X size={16}/></button></div>
    <div className="prepared-grid">
      <article><FileEdit size={18} aria-hidden/>
        <h3>{drafts.length ? `${drafts.length} strategy draft${drafts.length > 1 ? "s" : ""} from your words` : "Strategy, ready to write"}</h3>
        <p className="muted">{drafts.length ? `${drafts.map(k => sectionTitles[k]).join(", ")}. They stay drafts until you save them.` : "Five sections. Write them in any order; autosave keeps your work."}</p>
        <Link className="plate-link" href={`${base}/strategy?section=${drafts[0] ?? "icp"}`}>{drafts.length ? "Review drafts" : "Open strategy"}<ArrowRight size={14} aria-hidden/></Link></article>
      <article><Route size={18} aria-hidden/>
        <h3>{tasks ? `${tasks} tasks for your first 30 days` : "Your 30-day plan"}</h3>
        <p className="muted">{tasks ? "Generated by visible rules from what you saved. It sharpens as you complete the strategy." : "Generate it any time from the roadmap."}</p>
        <Link className="plate-link" href={`${base}/roadmap`}>Open roadmap<ArrowRight size={14} aria-hidden/></Link></article>
      <article className={run ? "ai-on" : ""}><Sparkles size={18} aria-hidden/>
        <h3>{!ai ? "AI specialists" : !ai.configured ? "AI not configured here" : !ai.authorized ? "AI specialists are locked" : run ? (["completed", "needs_attention"].includes(run.status) ? "AI proposals are ready" : run.status === "failed" ? "The AI run stopped" : "AI specialists are working") : "AI specialists are ready"}</h3>
        <p className="muted">{!ai?.configured ? "Everything here runs on transparent rules." : !ai.authorized ? "Unlock with the owner’s code to research and review your strategy." : run ? "Compare each proposal with what you saved, then apply what you agree with." : "Start a review from the AI page."}</p>
        {ai?.configured && <Link className="plate-link" href={`${base}/ai`}>{run && ["completed", "needs_attention"].includes(run.status) ? "Review proposals" : "Open AI specialists"}<ArrowRight size={14} aria-hidden/></Link>}</article>
    </div>
  </motion.section>;
}
